const canvas =
    document.getElementById(
        "webglCanvas"
    );


if (
    canvas
    &&
    typeof THREE !==
    "undefined"
) {

    const scene =
        new THREE.Scene();


    const camera =
        new THREE.PerspectiveCamera(
            45,
            window.innerWidth /
            window.innerHeight,
            0.1,
            100
        );


    camera.position.set(
        0,
        0,
        8
    );


    const renderer =
        new THREE.WebGLRenderer({

            canvas:
                canvas,

            alpha:
                true,

            antialias:
                true

        });


    renderer.setPixelRatio(
        Math.min(
            window.devicePixelRatio,
            2
        )
    );


    renderer.setSize(
        window.innerWidth,
        window.innerHeight
    );



    /* PARTICLES */

    const particleCount =
        1800;


    const particlePositions =
        new Float32Array(
            particleCount * 3
        );


    for (
        let i = 0;
        i < particleCount;
        i++
    ) {

        const i3 =
            i * 3;


        particlePositions[
            i3
        ] =
            (
                Math.random() -
                0.5
            ) * 24;


        particlePositions[
            i3 + 1
        ] =
            (
                Math.random() -
                0.5
            ) * 18;


        particlePositions[
            i3 + 2
        ] =
            (
                Math.random() -
                0.5
            ) * 18;

    }


    const particleGeometry =
        new THREE.BufferGeometry();


    particleGeometry.setAttribute(

        "position",

        new THREE.BufferAttribute(
            particlePositions,
            3
        )

    );


    const particleMaterial =
        new THREE.PointsMaterial({

            size:
                0.018,

            transparent:
                true,

            opacity:
                0.72,

            depthWrite:
                false,

            blending:
                THREE.AdditiveBlending

        });


    const particles =
        new THREE.Points(
            particleGeometry,
            particleMaterial
        );


    scene.add(
        particles
    );



    /* WIREFRAME */

    const shapeGeometry =
        new THREE.IcosahedronGeometry(
            1.75,
            2
        );


    const shapeMaterial =
        new THREE.MeshBasicMaterial({

            wireframe:
                true,

            transparent:
                true,

            opacity:
                0.065

        });


    const wireShape =
        new THREE.Mesh(
            shapeGeometry,
            shapeMaterial
        );


    wireShape.position.set(
        3.2,
        0.2,
        -1
    );


    scene.add(
        wireShape
    );



    /* RINGS */

    const ringGroup =
        new THREE.Group();


    for (
        let i = 0;
        i < 3;
        i++
    ) {

        const geometry =
            new THREE.TorusGeometry(
                2.6 +
                i * 0.55,
                0.006,
                8,
                160
            );


        const material =
            new THREE.MeshBasicMaterial({

                transparent:
                    true,

                opacity:
                    0.06

            });


        const ring =
            new THREE.Mesh(
                geometry,
                material
            );


        ring.rotation.x =
            Math.random() *
            Math.PI;


        ring.rotation.y =
            Math.random() *
            Math.PI;


        ringGroup.add(
            ring
        );

    }


    ringGroup.position.set(
        3,
        0,
        -2
    );


    scene.add(
        ringGroup
    );



    const mouse = {
        x: 0,
        y: 0
    };


    window.addEventListener(
        "pointermove",
        event => {

            mouse.x =
                (
                    event.clientX /
                    window.innerWidth
                    -
                    0.5
                );


            mouse.y =
                (
                    event.clientY /
                    window.innerHeight
                    -
                    0.5
                );

        }
    );


    const clock =
        new THREE.Clock();



    function animate() {

        requestAnimationFrame(
            animate
        );


        const elapsed =
            clock.getElapsedTime();


        particles.rotation.y =
            elapsed *
            0.008;


        particles.rotation.x =
            Math.sin(
                elapsed *
                0.05
            ) *
            0.04;


        wireShape.rotation.x =
            elapsed *
            0.05;


        wireShape.rotation.y =
            elapsed *
            0.075;


        ringGroup.rotation.y =
            elapsed *
            0.025;


        camera.position.x +=
            (
                mouse.x *
                0.5
                -
                camera.position.x
            ) *
            0.025;


        camera.position.y +=
            (
                -mouse.y *
                0.35
                -
                camera.position.y
            ) *
            0.025;


        camera.lookAt(
            0,
            0,
            0
        );


        renderer.render(
            scene,
            camera
        );

    }


    animate();



    window.addEventListener(
        "resize",
        () => {

            camera.aspect =
                window.innerWidth /
                window.innerHeight;


            camera.updateProjectionMatrix();


            renderer.setSize(
                window.innerWidth,
                window.innerHeight
            );

        }
    );

}



