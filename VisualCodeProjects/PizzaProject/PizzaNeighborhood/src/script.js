function setCardBackground(
    element,
    project
) {

    const fallback =
        categoryBackgrounds[
            project.category
        ]
        ||
        categoryBackgrounds.xr;


    element.style.backgroundImage =
        fallback;


    if (
        !project.image
    ) {
        return;
    }


    const image =
        new Image();


    image.onload =
        () => {

            element.style.backgroundImage = `

                linear-gradient(
                    to top,
                    rgba(7,10,18,.35),
                    rgba(7,10,18,.05)
                ),

                url("${project.image}")

            `;

        };


    image.onerror =
        () => {

            element.style.backgroundImage =
                fallback;

        };


    image.src =
        project.image;

}



