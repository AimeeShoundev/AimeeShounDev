function renderProjects() {

    if (
        !projectGrid
    ) {
        return;
    }


    projectGrid.innerHTML =
        "";


    const filtered =
        projects.filter(
            project => {

                const categoryMatch =
                    activeFilter === "all"
                    ||
                    project.category === activeFilter;


                const searchable = `

                    ${project.title}

                    ${project.collection}

                    ${project.type}

                    ${project.description}

                    ${project.contribution}

                    ${project.tags.join(" ")}

                `
                .toLowerCase();


                const searchMatch =
                    searchable.includes(
                        searchTerm
                    );


                return (
                    categoryMatch
                    &&
                    searchMatch
                );

            }
        );


    filtered.forEach(
        (
            project,
            index
        ) => {

            projectGrid.appendChild(
                createProjectCard(
                    project,
                    index
                )
            );

        }
    );


    if (
        visibleProjectCount
    ) {

        visibleProjectCount.textContent =
            filtered.length;

    }

}



